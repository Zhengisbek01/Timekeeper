// текст документа одной строкой — для хеша, который сохраняется вместе с согласием
export const docText = (d) => [d.title, `Редакция ${d.version} от ${d.date}`, ...d.sections.flatMap((s) => [s.h, ...s.p])].join('\n')

export async function docHash(d) {
  try {
    const buf = await crypto.subtle.digest('SHA-256', new TextEncoder().encode(docText(d)))
    return Array.from(new Uint8Array(buf), (b) => b.toString(16).padStart(2, '0')).join('')
  } catch { return null }
}
